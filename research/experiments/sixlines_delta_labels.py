#!/usr/bin/env python
"""
sixlines_delta_labels.py -- the invariant delta of note 23 against the CM method of note 20 (note 24).

Note 23 computes, for the surfaces of three polynomials, a sign delta from a self-pairing on the 16-torsion of the
Prym variety, and conjectures that it is the character chi_{-1} of G ("the degree of the step modulo 4", note 19):
delta(g X) = chi_{-1}(g) delta(X).  Note 20 computes the action of G on the lattices of the surfaces, by ideals above
primes l = 1 mod 4.  For such an ideal chi_{-1} = (-1/l) = 1, so these ideals move a lattice inside a coset of
ker chi_{-1}.  Prediction: delta is constant on each orbit of these ideals and differs between the two orbits.

What the script does for one polynomial (q, e1, mu, nu):

  1. the even lattices of each of the three types and their period points (sixlines_cmmethod.Torsor; the period
     points are computed in parallel here, nothing else is changed), the class polynomial H over E and its reduction
     at the prime (q, F - e1): its roots are the surfaces over F_q;
  2. the permutations of the lattices induced by the six ideals P_j P_k conj(P_l P_m) above each of a few primes
     l = 1 mod 4, the group they generate and its orbits on the lattices of each type;
  3. if there are two orbits: the polynomial I_T(X) = sum_j s_T(j) prod_{l != j} (X - x_l), s_T = +1 on one orbit and
     -1 on the other.  The function s on the roots of H is fixed by the group of step 2 and negated by the rest of G,
     so s = sqrt(d) * (element of E) with E(sqrt(d)) the quadratic extension of E cut out by the character.  For
     d = -1 the three polynomials I_T / i, with a sign for each type, are the images of one polynomial Gamma over E.
     The script tries the divisors 1 and i and the four choices of signs and takes the one that is recognised.
     Modulo the prime, Gamma(r) / H'(r) is one of the two square roots of 1/d at each root r: that is the orbit of the
     surface r.  (The check that these values are square roots of -1 is a check of d = -1.)
  4. delta for each surface, from sixlines_jacobian_character.jsonl and sixlines_jacobian_character_extra.jsonl,
     against the orbit.

  run q e1 mu nu [--digits D ...] [--primes n] [--workers w] [--out file]

If none of the eight coordinates of sixlines_cmmethod separates the surfaces modulo q, pseudo-random integer
combinations of the invariants are tried, from a fixed seed, with the same acceptance rule (setup_more).

Uses cypari2 through sixlines_cmmethod.  Class groups are PARI's without certification (GRH).  Run from experiments/
with python -I.
"""
import argparse
import json
import os
import sys
import time
from multiprocessing import get_context

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sixlines_cmmethod as cm  # noqa: E402

pari = cm.pari
HERE = cm.HERE
TYPES = cm.TYPES
WORKERS = 4
_CTX = None


def _point(i):
    fld, pl, R2, lats = _CTX
    lat = lats[i]
    t0 = time.time()
    tau = fld.tau(lat, pl)
    imag = pari("t -> (t - conj(t~)) / (2 * I)")
    Y = imag(tau)
    assert float(pari.real(Y[0, 0])) > 0 and float(pari.real(pari.matdet(Y))) > 0, "tau not in D"
    taur = cm.G("cm_reduce")(tau)
    J = cm.G("cm_J")(cm.G("cm_tsq")(taur, R2))
    return str(taur), str(J), float(pari.real(pari.matdet(imag(taur)))), time.time() - t0


def parallel_cm_points(fld, digits, verbose=True, order=True, level=True):
    """cm.cm_points with the period points computed in forked workers."""
    global _CTX
    cm.setprec(digits + 20)
    R2 = cm.R2_for(digits)
    pl = fld.embeddings()
    lats = fld.order_lattices(verbose, level) if order else fld.lattices()
    idx = [i for i, lat in enumerate(lats) if lat["T"] is not None]
    for lat in lats:
        lat["J"] = None
    _CTX = (fld, pl, R2, lats)
    t0 = time.time()
    with get_context("fork").Pool(WORKERS) as pool:
        res = pool.map(_point, idx, chunksize=1)
    for i, (taus, Js, detY, sec) in zip(idx, res):
        lats[i]["tau"] = pari(taus)
        lats[i]["J"] = pari(Js)
        lats[i]["detY"] = detY
    print(f"  {len(idx)} period points at {digits} digits: {time.time() - t0:.0f} s wall, "
          f"{sum(r[3] for r in res):.0f} s of processor time", flush=True)
    return lats


cm.cm_points = parallel_cm_points


def closure(gens, n):
    """The group of permutations of range(n) generated by gens, as a set of tuples."""
    ident = tuple(range(n))
    seen = {ident}
    todo = [ident]
    while todo:
        g = todo.pop()
        for h in gens:
            k = cm.compose(h, g)
            if k not in seen:
                seen.add(k)
                todo.append(k)
    return seen


def orbits(group, n):
    out, left = [], set(range(n))
    while left:
        j = min(left)
        orb = sorted({g[j] for g in group})
        out.append(orb)
        left -= set(orb)
    return out


def load_delta(q):
    """{configuration: set of delta over the pairs of lines computed} from the two files of note 23."""
    out = {}
    for name in ("sixlines_jacobian_character.jsonl", "sixlines_jacobian_character_extra.jsonl"):
        with open(os.path.join(HERE, name)) as fh:
            for line in fh:
                r = json.loads(line)
                if r["p"] == q and r.get("status") == "ok" and "delta" in r:
                    out.setdefault(tuple(r["cfg"]), []).append(r["delta"])
    return out


def setup_more(tor, q, bq, tries=300):
    """Torsor.setup with more coordinates: the eight of sixlines_cmmethod can all have two surfaces with the same
    value modulo q when q is small and there are twelve surfaces.  Same acceptance rule; the coordinates are
    pseudo-random integer combinations of the invariants of the chart, from a fixed seed."""
    import random
    rng = random.Random(82)
    EP = tor.prime(q, bq)
    prod = pari("v -> my(P = 1); for(k = 1, #v, P *= ('X - v[k])); P")
    for chart in ("J2", "J3"):
        tor.set_chart(chart)
        n = len(tor.pts[0]["inv"])
        for _ in range(tries):
            mix = [rng.randint(-9, 9) for _ in range(n)]
            xs = tor.coordinate(mix)
            H = tor.rec.poly([prod(xs[T]) for T in TYPES])
            if H is None:
                continue
            Hq = cm.reduce_poly(H, EP)
            if Hq is None:
                break                      # a surface outside the chart: no coordinate of this chart will do
            if pari.poldegree(pari.gcd(Hq, pari.deriv(Hq))) != 0 or len(pari.polrootsmod(Hq, q)) != tor.N:
                continue
            tor.mix, tor.xs, tor.H = mix, xs, H
            tor.Gs = tor.invariant_polys()
            if any(g is None for g in tor.Gs) or any(cm.reduce_poly(g, EP) is None for g in tor.Gs):
                print(f"  chart {chart}, coordinate {mix}: the polynomials of the invariants are not recognised", flush=True)
                tor.mix = None
                return False
            print(f"  chart {chart}, coordinate {mix}: {tor.N} simple roots modulo {q}", flush=True)
            return True
    return False


def run_one(q, e1, mu, nu, digits, nprimes):
    rec = {"q": q, "e1": e1, "mu": mu, "nu": nu, "digits": digits}
    fld = cm.CMField(q, e1, mu, nu)
    t0 = time.time()
    tor = cm.Torsor(fld, digits, verbose=False)
    N = tor.N
    rec["N"] = N
    print(f"q = {q}, e1 = {e1}: {N} even lattices per type, digits {digits}", flush=True)
    if not tor.setup(q, e1 % q, verbose=True) and not setup_more(tor, q, e1 % q):
        rec["status"] = "class polynomial not obtained"
        print("  class polynomial not obtained", flush=True)
        return rec
    print(f"  class polynomial recognised, chart {tor.chart}, coordinate {tor.mix}, {time.time() - t0:.0f} s", flush=True)
    rec.update({"chart": tor.chart, "coordinate": tor.mix})

    # the surfaces
    EPq = tor.prime(q, e1 % q)
    red = cm.reduced_points(tor, q, e1 % q)
    enum_set = cm.enumerated_points(q, e1, tor.e2, tor.chart)
    roots = sorted(red)
    rec["surfaces_in_both"] = sum(1 for r in roots if red[r] in enum_set)
    rec["enumerated_points"] = len(enum_set)
    assert len(roots) == N

    # the group generated by the ideals above primes l = 1 mod 4
    nf = pari("b -> b.nf")(fld.bnf)
    primes = cm.split_primes(fld, tor, nprimes)
    gens = {T: [] for T in TYPES}
    classes = set()
    for P in primes:
        for pr in cm.PAIRS:
            sub = (1 << pr[0]) | (1 << pr[1])
            perms = tor.act(cm.G("k_ideal")(nf, P["prs"], sub), P["l"])
            classes.add(tuple(int(x) for x in cm.G("e_class")(tor.ES, P["b"][pr], P["l"])))
            for T in TYPES:
                gens[T].append(perms[T])
        print(f"  l = {P['l']}: done, {time.time() - t0:.0f} s", flush=True)
    groups = {T: closure(gens[T], N) for T in TYPES}
    orbs = {T: orbits(groups[T], N) for T in TYPES}
    rec.update({"primes": [P["l"] for P in primes], "classes_seen": len(classes),
                "group_order": [len(groups[T]) for T in TYPES], "orbits": [[len(o) for o in orbs[T]] for T in TYPES]})
    print(f"  primes {rec['primes']}: {len(classes)} classes of G seen; the permutations generate groups of order "
          f"{rec['group_order']} with orbits of sizes {rec['orbits']}", flush=True)
    if any(len(orbs[T]) != 2 for T in TYPES):
        rec["status"] = "the ideals above primes 1 mod 4 do not have two orbits"
        return rec

    # the indicator of an orbit as a polynomial over E
    I = {}
    for T in TYPES:
        s = [1 if j in orbs[T][0] else -1 for j in range(N)]
        I[T] = cm.interpolation_poly(tor.xs[T], s)
    found = []
    for name, div in (("1", pari(1)), ("i", pari("I"))):
        for e2 in (1, -1):
            for e3 in (1, -1):
                Gam = tor.rec.poly([I[TYPES[0]] / div, e2 * I[TYPES[1]] / div, e3 * I[TYPES[2]] / div])
                if Gam is not None:
                    found.append((name, e2, e3, Gam))
    rec["indicator_recognised"] = [[f[0], f[1], f[2]] for f in found]
    print(f"  indicator of an orbit: recognised over E for (divisor, signs) = {rec['indicator_recognised']}", flush=True)
    if len(found) != 1:
        rec["status"] = "indicator not recognised" if not found else "indicator recognised in more than one way"
        return rec
    name, _, _, Gam = found[0]
    Gq = cm.reduce_poly(Gam, EPq)
    if Gq is None:
        rec["status"] = "indicator not integral at the prime"
        return rec
    Hq = cm.reduce_poly(tor.H, EPq)
    dH = pari.deriv(Hq)
    val = {r: int(pari.lift(pari.subst(Gq, "X", pari.Mod(r, q)) / pari.subst(dH, "X", pari.Mod(r, q)))) for r in roots}
    target = (-1) % q if name == "i" else 1
    rec["divisor"] = name
    rec["values_square_to"] = sorted({v * v % q for v in val.values()})
    ok_sq = all(v * v % q == target for v in val.values())
    print(f"  Gamma / H' at the roots: {val}; squares {rec['values_square_to']} (expected {target}): {ok_sq}", flush=True)
    if not ok_sq:
        rec["status"] = "values of the indicator are not square roots of 1/d"
        return rec
    v0 = min(val.values())
    coset = {r: 0 if val[r] == v0 else 1 for r in roots}

    # delta
    delta = load_delta(q)
    rows = []
    for r in roots:
        cfgs = enum_set.get(red[r], [])
        ds = [d for c in cfgs for d in delta.get(tuple(c), [])]
        rows.append({"root": r, "invariants": list(red[r]), "configurations": [list(c) for c in cfgs], "orbit": coset[r],
                     "delta": sorted(set(ds)), "pairs": len(ds)})
        print(f"     root {r:3d}  orbit {coset[r]}  delta {sorted(set(ds))} from {len(ds)} pairs  configurations {cfgs}")
    rec["surfaces"] = rows
    by = {0: set(), 1: set()}
    for row in rows:
        by[row["orbit"]].update(row["delta"])
    rec["orbit_sizes"] = [sum(1 for row in rows if row["orbit"] == k) for k in (0, 1)]
    rec["delta_by_orbit"] = [sorted(by[0]), sorted(by[1])]
    rec["surfaces_with_delta"] = sum(1 for row in rows if len(row["delta"]) == 1)
    rec["agrees"] = bool(len(by[0]) == 1 and len(by[1]) == 1 and by[0] != by[1]
                         and rec["surfaces_with_delta"] == N)
    rec["status"] = "ok"
    print(f"  orbits of sizes {rec['orbit_sizes']}; delta on the two orbits: {rec['delta_by_orbit']}; "
          f"delta is constant on each orbit and differs between them: {rec['agrees']}", flush=True)
    return rec


def main():
    global WORKERS
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("run")
    s.add_argument("q", type=int)
    s.add_argument("e1", type=int)
    s.add_argument("mu", type=int)
    s.add_argument("nu", type=int)
    s.add_argument("--digits", type=int, nargs="+", default=[1200])
    s.add_argument("--primes", type=int, default=3)
    s.add_argument("--workers", type=int, default=4)
    s.add_argument("--out")
    a = ap.parse_args()
    WORKERS = a.workers
    rec = None
    for digits in a.digits:
        rec = run_one(a.q, a.e1, a.mu, a.nu, digits, a.primes)
        if rec.get("status") == "ok":
            break
        print(f"  status at {digits} digits: {rec.get('status')}", flush=True)
    if a.out:
        with open(a.out, "a") as fh:
            fh.write(json.dumps(rec) + "\n")


if __name__ == "__main__":
    main()
