def canonical_keys(pts, p):
    """Least code of (b, c, e, f) over the 720 orderings; pts is (n, 6, 3).  -1 where some ordering degenerates."""
    inv = np.array([0] + [pow(a, p - 2, p) for a in range(1, p)], dtype=np.int64)
    best = np.full(len(pts), p ** 4, dtype=np.int64)
    bad = np.zeros(len(pts), dtype=bool)
    for perm in itertools.permutations(range(6)):
        q = pts[:, perm, :]
        cr = [np.cross(q[:, 1], q[:, 2]) % p, np.cross(q[:, 2], q[:, 0]) % p, np.cross(q[:, 0], q[:, 1]) % p]
        lam = [np.einsum("ij,ij->i", cr[i], q[:, 3]) % p for i in range(3)]
        mu = [lam[1] * lam[2] % p, lam[0] * lam[2] % p, lam[0] * lam[1] % p]
        img = []
        for j in (4, 5):
            x = [mu[i] * (np.einsum("ij,ij->i", cr[i], q[:, j]) % p) % p for i in range(3)]
            bad |= (x[0] == 0)
            s = inv[x[0]]
            img.append((x[1] * s % p, x[2] * s % p))
        key = ((img[0][0] * p + img[0][1]) * p + img[1][0]) * p + img[1][1]
        np.minimum(best, key, out=best)
    best[bad] = -1
    return best


def encode(cfg, p):
    b, c, e, f = cfg
    return ((b * p + c) * p + e) * p + f


def conjugate_lines(p, forms, pair):
    """The lines through L5 n L6 conjugate to L5 and to L6 under the involution of the cross-ratio map, or None."""
    import sixlines_prym as sp
    rest = [i for i in range(1, 7) if i not in pair]
    L = pari.matrix(6, 3, [x for row in forms for x in row])
    N, D = sp.GP["pr_lambda"](L, rest + list(pair), p)
    r = CONJ(N, D, p)
    if r == 0:
        return None
    t5, t6 = int(r[0]), int(r[1])
    if t5 == 0 or t6 == 0 or t5 == t6:
        return None
    l5, l6 = forms[pair[0] - 1], forms[pair[1] - 1]
    return [tuple((l5[i] - t * l6[i]) % p for i in range(3)) for t in (t5, t6)]


def run_association(primes):
    import sixlines_prym as sp
    global CONJ
    CONJ = pari(r"""(N, D, p) -> my(l5, l6, f5, f6);
        if(subst(D, 't, 0) == 0 || polcoef(D, 2) == 0, return(0));
        l5 = subst(N, 't, 0) / subst(D, 't, 0); l6 = polcoef(N, 2) / polcoef(D, 2);
        f5 = N - l5 * D; f6 = N - l6 * D;
        if(polcoef(f5, 2) == 0 || polcoef(f6, 1) == 0, return(0));
        [lift(-polcoef(f5, 1) / polcoef(f5, 2)), lift(-polcoef(f6, 0) / polcoef(f6, 1))]""")
    total = Counter()
    for p in primes:
        rows = [json.loads(line) for line in open(os.path.join(HERE, f"sixlines_p{p}.jsonl"))]
        pts, meta = [], []
        stats = Counter()
        for r in rows:
            forms = sp.forms(r["cfg"])
            for pair in itertools.combinations(range(1, 7), 2):
                stats["pairs"] += 1
                cl = conjugate_lines(p, forms, pair)
                if cl is None:
                    stats["no conjugate lines"] += 1
                    continue
                pts.append([forms[i - 1] for i in range(1, 7) if i not in pair] + cl)
                meta.append((encode(r["cfg"], p), encode(r["assoc"], p)))
        if pts:
            keys = canonical_keys(np.array(pts, dtype=np.int64), p)
            for k, (own, assoc) in zip(keys, meta):
                if k == -1:
                    stats["new configuration not in general position"] += 1
                elif k == assoc:
                    stats["associated configuration"] += 1
                    stats["of which self-associated"] += (own == assoc)
                elif k == own:
                    stats["same configuration, not self-associated"] += 1
                else:
                    stats["another configuration"] += 1
        print(f"p = {p}: {dict(sorted(stats.items()))}", flush=True)
        total += stats
    print(f"total: {dict(sorted(total.items()))}")


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    d = sub.add_parser("dictionary")
    d.add_argument("--bound", type=int, default=2000)
    d.add_argument("--workers", type=int, default=8)
    d.add_argument("--out")
    d.add_argument("--limit", type=int, default=0)
    a = sub.add_parser("association")
    a.add_argument("primes", nargs="+", type=int)
    args = ap.parse_args()
    if args.cmd == "dictionary":
        run_dictionary(args)
    else:
        run_association(args.primes)


if __name__ == "__main__":
    main()
