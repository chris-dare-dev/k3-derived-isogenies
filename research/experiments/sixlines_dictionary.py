HERE = os.path.dirname(os.path.abspath(__file__))

pari(r"""
dc_up(bnf, bnf0, s, I) = {
  \\ the ideal of bnf generated by the ideal I of the subfield bnf0 = Q(s)
  my(two = idealtwoelt(bnf0, I));
  idealhnf(bnf, two[1], subst(lift(nfbasistoalg(bnf0, two[2])), 'x, s));
}
""")

pari(r"""
dc_sub(bnf, s, ram) = {
  \\ the subfield Q(s) of index 2 and the lattice in Z^k (columns, containing the relations of Cl(bnf)) of the
  \\ classes extended from it, plus (ram = 1) the primes of bnf ramified over it.  Returns [M, class number below].
  my(nf = bnf.nf, h = minpoly(s, 'x), bnf0 = bnfinit(h, 1), cyc = bnf.cyc, k = #cyc, M, rm);
  if(k == 0, return([matrix(0, 0), bnf0.no]));
  M = matdiagonal(cyc);
  for(j = 1, #bnf0.gen, M = concat(M, Mat(bnfisprincipal(bnf, dc_up(bnf, bnf0, s, bnf0.gen[j]), 0))));
  if(ram,
    rm = abs(nf.disc) / bnf0.disc^2;
    foreach(factor(rm)[, 1]~, l,
      foreach(idealprimedec(bnf0, l), pr,
        my(fa = idealfactor(nf, dc_up(bnf, bnf0, s, pr)));
        if(matsize(fa)[1] == 1 && fa[1, 2] == 2, M = concat(M, Mat(bnfisprincipal(bnf, fa[1, 1], 0)))))));
  [mathnf(M), bnf0.no];
}
""")

pari(r"""
dc_one(P, q, e1, mu, nu, B) = {
  \\ see the module docstring.  Returns 0 if chi conj(chi) is reducible, else a vector of results.
  my(a = 4 * (nu + mu * I), chi = 'X^4 - a * 'X^3 + e1 * 'X^2 - q * conj(a) * 'X + q^2, W8 = real(chi * conj(chi)),
     t = variable(P), bnfK, bnfE, io = 0, piK, pp = factor(q)[1, 1], bad, cK, cE, kK, kE, U, W, n = 0, il, chil, a0, aa, idK, idE, Q, Pa,
     hn, X, F, ok_gen, ok_hom = 1, ok_rel = 1, subK, subE, LK, HE, ok_sub, dom, tgt, coker, res, primes = 0, lmax = 0);
  if(imag(chi * conj(chi)) != 0 || !polisirreducible(W8), return(0));
  bnfK = bnfinit(W8, 1); bnfE = bnfinit(P, 1);
  piK = Mod('X, W8);
  foreach(nfroots(bnfK, 'x^2 + 1), z,
    if(piK^4 - 4 * (nu + mu * z) * piK^3 + e1 * piK^2 - 4 * q * (nu - mu * z) * piK + q^2 == 0, io = z));
  if(io === 0, error("i not found in K"));
  cK = bnfK.cyc; cE = bnfE.cyc; kK = #cK; kE = #cE;
  bad = bnfE.nf.disc * bnfK.nf.disc * poldisc(P) * poldisc(W8) * q;
  U = matrix(kK, 0); W = matrix(kE, 0);
  forprime(l = 5, B,
    if(l % 4 != 1 || bad % l == 0, next);
    foreach([1, -1], sg,
      il = sg * lift(sqrt(Mod(-1, l)));
      chil = Mod(1, l) * 'x^4 - 4 * (nu + mu * il) * 'x^3 + e1 * 'x^2 - 4 * q * (nu - mu * il) * 'x + q^2;
      foreach(polrootsmod(chil, l), a0,
        aa = lift(a0);
        idK = idealadd(bnfK, idealadd(bnfK, l, io - il), piK - aa);
        if(idealnorm(bnfK, idK) != l, error("the prime of K does not have norm l"));
        Q = chil / ('x - a0);
        Pa = lift(a0^3 * subst(Q, 'x, 'x / a0));
        idE = idealadd(bnfE, l, Mod(subst(Pa, 'x, t), P));
        if(idealnorm(bnfE, idE) != l^3, error("the image ideal does not have norm l^3"));
        U = concat(U, Mat(bnfisprincipal(bnfK, idK, 0)));
        W = concat(W, Mat(bnfisprincipal(bnfE, idE, 0)));
        n++; lmax = l)));
  \\ generation, and the matrix F of f on the generators of Cl(K)
  if(kK == 0,
    ok_gen = 1; F = matrix(kE, 0);
    for(j = 1, n, for(r = 1, kE, if(W[r, j] % cE[r] != 0, ok_hom = 0))),
    hn = mathnf(concat(U, matdiagonal(cK)), 1);
    ok_gen = (hn[1] == matid(kK));
    if(ok_gen,
      X = matrix(n, kK, r, c, hn[2][r, n + c]);
      F = W * X;
      \\ f([PP]) = [Psi(PP)] for every prime, and f respects the relations of Cl(K)
      for(j = 1, n, my(d = F * U[, j] - W[, j]); for(r = 1, kE, if(d[r] % cE[r] != 0, ok_hom = 0)));
      for(c = 1, kK, for(r = 1, kE, if((cK[c] * F[r, c]) % cE[r] != 0, ok_rel = 0)))));
  if(!ok_gen, return([0, n, lmax, cK, cE]));
  subK = dc_sub(bnfK, piK + q / piK, 0);
  subE = dc_sub(bnfE, Mod(t, P) + q^2 / Mod(t, P), 1);
  LK = if(kK, subK[1], matrix(0, 0)); HE = if(kE, subE[1], matrix(0, 0));
  \\ f(L_K) inside H_E
  ok_sub = 1;
  if(kK && kE, my(Z = HE^(-1) * (F * LK)); ok_sub = (denominator(Z) == 1));
  dom = if(kK, matdet(LK), 1); tgt = if(kE, matdet(HE), 1);
  coker = if(kE, if(kK, matdet(mathnf(concat(HE, F))), tgt), 1);
  [1, n, lmax, cK, cE, ok_hom, ok_rel, ok_sub, dom, tgt, coker,
   if(kK, select(d -> d > 1, matsnf(LK)), []), if(kE, select(d -> d > 1, matsnf(HE)), []), subK[2], subE[2]];
}
""")
GP_one = pari("dc_one")


def mu_nu(q, e):
    e1, e2, e3 = e
    c2, c3 = e2 - 3 * q * q, e3 - 2 * q * q * e1
    a = 8 * q ** 3 - 4 * q * q * e1 + 2 * q * c2 - c3
    b = 8 * q ** 3 + 4 * q * q * e1 + 2 * q * c2 + c3
    a, b = a // (64 * q * q), b // (64 * q * q)
    return math.isqrt(a), math.isqrt(b)


def odd_part(n):
    while n % 2 == 0:
        n //= 2
    return n


def dictionary_one(job):
    q, e, source, bound = job
    mu, nu = mu_nu(q, e)
    P = cm.pol(cm.charpoly(q, e))
    res = GP_one(P, q, e[0], mu, nu, bound)
    rec = {"q": q, "e": e, "mu_nu": [mu, nu], "source": source}
    if res == 0:
        rec["status"] = "chi conj(chi) reducible"
        return rec
    rec["primes"] = int(res[1])
    rec["largest_prime"] = int(res[2])
    rec["cyc_K"] = [int(x) for x in res[3]]
    rec["cyc_E"] = [int(x) for x in res[4]]
    if int(res[0]) == 0:
        rec["status"] = "primes do not generate Cl(K)"
        return rec
    rec["status"] = "ok"
    rec["homomorphism"] = bool(int(res[5])) and bool(int(res[6]))
    rec["subgroups_respected"] = bool(int(res[7]))
    rec["minus_K"] = int(res[8])
    rec["G"] = int(res[9])
    rec["cokernel"] = int(res[10])
    rec["kernel"] = rec["minus_K"] * rec["cokernel"] // rec["G"]
    rec["minus_K_cyc"] = sorted(int(x) for x in res[11])
    rec["G_cyc"] = sorted(int(x) for x in res[12])
    rec["h_K_plus"] = int(res[13])
    rec["h_E0"] = int(res[14])
    rec["odd_parts_equal"] = sorted(v for v in (odd_part(x) for x in rec["minus_K_cyc"]) if v > 1) == \
        sorted(v for v in (odd_part(x) for x in rec["G_cyc"]) if v > 1)
    return rec


def run_dictionary(args):
    jobs, seen = [], set()
    for line in open(os.path.join(HERE, "sixlines_cm.jsonl")):
        r = json.loads(line)
        jobs.append((r["p"], r["e"], "surfaces", args.bound))
        seen.add((r["p"], tuple(r["e"])))
    for line in open(os.path.join(HERE, "sixlines_groupsize.jsonl")):
        r = json.loads(line)
        if r.get("source") == "all" and r.get("maximal") and (r["q"], tuple(r["e"])) not in seen:
            jobs.append((r["q"], r["e"], "maximal order, q <= 101", args.bound))
            seen.add((r["q"], tuple(r["e"])))
    if args.limit:
        jobs = jobs[:args.limit]
    with Pool(args.workers) as pool:
        recs = pool.map(dictionary_one, jobs, chunksize=2)
    fh = open(args.out, "w") if args.out else None
    stats = Counter()
    ker, cok, ratio = Counter(), Counter(), Counter()
    for rec in recs:
        if fh:
            fh.write(json.dumps(rec) + "\n")
        stats["polynomials"] += 1
        stats[rec["status"]] += 1
        if rec["status"] != "ok":
            continue
        stats["one homomorphism matches all primes"] += rec["homomorphism"]
        stats["Cl(K+) goes into H"] += rec["subgroups_respected"]
        stats["odd parts of Cl-(K) and G isomorphic"] += rec["odd_parts_equal"]
        stats["Cl-(K) and G not both trivial"] += (rec["minus_K"] > 1 or rec["G"] > 1)
        stats["odd part of G not trivial"] += odd_part(rec["G"]) > 1
        stats["primes used"] += rec["primes"]
        ker[rec["kernel"]] += 1
        cok[rec["cokernel"]] += 1
        ratio[f'{rec["minus_K"]}/{rec["G"]}' if rec["minus_K"] != rec["G"] else "equal"] += 1
        if not (rec["homomorphism"] and rec["subgroups_respected"] and rec["odd_parts_equal"]):
            print("  FAILED:", rec, flush=True)
    print("dictionary:", dict(stats))
    print("  order of the kernel of Cl-(K) -> G:", dict(sorted(ker.items())))
    print("  order of the cokernel:", dict(sorted(cok.items())))
    big = max((r for r in recs if r["status"] == "ok"), key=lambda r: r["G"])
    print(f"  largest G: {big['G']} {big['G_cyc']} with Cl-(K) {big['minus_K']} {big['minus_K_cyc']}, q = {big['q']}, e = {big['e']}")


