#!/usr/bin/env python
"""
sixlines_dictionary.py -- the two class groups of a six-line surface and its fourfold, and association (note 15).

dictionary   For a polynomial P of note 13 with its quartic chi over Z[i] (P = second exterior power of chi):
             E = Q[t]/P of degree 6 and K = Q[X]/(chi conj(chi)) of degree 8.  A prime PP of K of degree 1 over
             l = 1 mod 4 is (l, i - i_l, pi - a) with a a root of chi mod (l, i - i_l).  The map of tori
             x -> (x_j x_k)_{j<k} sends it to the ideal

                 Psi(PP) = (l, P_a(t)),  P_a(t) = a^3 (chi / (X - a))(t / a) mod l,

             of norm l^3 in E: the product of the primes of E at the roots a b, b the other roots of chi.
             The script computes the classes of PP in Cl(K) and of Psi(PP) in Cl(E) for all such primes up to a
             bound, and checks that

               * the classes of the PP generate Cl(K);
               * there is one homomorphism f : Cl(K) -> Cl(E) with f([PP]) = [Psi(PP)] for all of them;
               * f maps the classes extended from K+ into H = <classes extended from E0, primes ramified over E0>,

             and then reports, for Cl-(K) = Cl(K) / Cl(K+) and G = Cl(E) / H (the group of note 13, Lemma 9):
             the orders, the elementary divisors, and the orders of the kernel and cokernel of Cl-(K) -> G.

             An isogeny of the fourfold with kernel A[aa], aa = PP_j PP_k conj(PP_m PP_n), corresponds under f to
             l times the step of the surface at the prime of E at the root a_j a_k, divided by its conjugate.

             Polynomials: the 44 of the enumerated surfaces (sixlines_cm.jsonl) and those of sixlines_groupsize.jsonl
             with maximal order from the exhaustive part of that run (q <= 101).

association  For every configuration of sixlines_p{p}.jsonl and every pair of lines: replace both lines of the
             pair by their conjugates under the involution of the cross-ratio map of note 14 and identify the
             resulting configuration.  It is the associated configuration (or the configuration is skipped as
             degenerate).  The curve of note 14 depends only on the cross-ratio map and its two values, so the
             configuration and its associate have the same curve.

PARI's bnfinit is used without certification, so class groups are correct under GRH.

  python -I sixlines_dictionary.py dictionary [--bound B] [--workers n] [--out FILE] [--limit n]
  python -I sixlines_dictionary.py association p [p ...]

Run from experiments/.
"""
import argparse
import itertools
import json
import math
