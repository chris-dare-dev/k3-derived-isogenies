#!/usr/bin/env python
"""
sixlines_rank6.py -- eigenvalue +-q of multiplicity 6 with l^4 exactly dividing P(+-q) (note 11).

Setting: an odd prime l prime to q, lam = +-q a root of P mod l of multiplicity 6, and exactly l^4
dividing P(lam).  tau = (F - lam)/(F + lam), g = F / lam.  Note 11 states, for the unimodular F-stable
lattices L at l:

  (1) patterns:  the valuations of F - lam on the three pairs of eigenvalues, with v(l) = 1, are
                 (1, 1/2, 1/2), (1/2, 3/4, 3/4), (3/2, 1/4, 1/4) or (2/3, 2/3, 2/3);
  (2) kinds:     the Jordan blocks of tau on L / l L are (1,5) ("leaf", one step), (3,3) ("middle",
                 l + 1 steps), (1,1,1,3) or (1,1,2,2) ("wide", L / tau L = (Z/l)^4); a leaf is joined to
                 a lattice that is not a leaf, or to one other leaf and nothing else;
  (3) wide:      the wide lattices are the unimodular lattices stable under l / tau, which satisfies
                 the hypothesis of notes 8 and 9; so they form a tree (finite cases), or are absent;
  (4) two:       in the pattern (3/2, 1/4, 1/4) there are exactly two lattices, joined by a step;
  (5) quartic:   if -P(q) P(-q) is a square in Q_l, let kappa in {1, non-residue} with kappa q P(-lam)
                 a square, s+ = sqrt(kappa^3 P(-lam) / lam^3), s- = sqrt(-kappa^3 P(lam) / lam^3) and
                     f = x^4 - a x^3 + kappa e1' x^2 - d x + (q kappa)^2,
                     a = (s+ + s-) / (2 q kappa),  d = (s+ - s-) / 2,
                 (e1' the trace of F / lam times q).  Then the lattices L correspond to the homothety
                 classes of lattices in Q_l[x] / f stable under x, of one parity, and the steps to the
                 pairs  l Lam < Lam' < Lam  of index l^2.

For every polynomial t^3 h(t + q^2/t) found (h a cubic with three real roots in (-2q, 2q), irreducible,
multiplicity 6, exactly l^4), the script chooses forms with a unimodular lattice of the simplest kind,
follows the steps (the whole component if no prime is a pair, a ball otherwise), and asserts (1), (2),
(4), the tree statement of (3) in the finite cases, and, when -P(q)P(-q) is a square, (5): equality of
colour-refinement invariants of the two graphs (finite cases), or of the balls of radius 3 around a
leaf and around the lattice Z_l[x] (infinite cases).  The local rule (O) of note 10 is tested on
every lattice met.

  python -I sixlines_rank6.py [--out FILE] [--search q,l ...] [--forms K] [--both-signs]

Run from experiments/.  Default: q = 5 with l = 3, eigenvalue +q.
"""
import argparse
import json
import os
import sys
from collections import Counter
from fractions import Fraction

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sixlines_cm as cm  # noqa: E402
from sixlines_cm import pari  # noqa: E402
import sixlines_vertical as sv  # noqa: E402
import sixlines_deep as dp  # noqa: E402

pari(r"""
r6_quartic(P, q, sgn, l, prec) = {
  \\ [split, f]: the quartic of (5), with coefficients lifted from Z_l to Z
  my(t = variable(P), lam = sgn * q, G = subst(P, t, sgn * t) , e1 = -polcoef(G, 5), Pm = subst(G, t, -q),
     Pp = subst(G, t, q), kap, sp, sm, a, d, nr = 2);
  \\ G is the polynomial of sgn F, whose eigenvalue is q
  while(kronecker(nr, l) != -1, nr++);
  kap = if(issquare(q * Pm + O(l^prec)), 1, nr);
  if(!issquare(-kap * q * Pp + O(l^prec)), return([0, 0]));
  sp = sqrt(kap^3 * Pm / q^3 + O(l^prec)); sm = sqrt(-kap^3 * Pp / q^3 + O(l^prec));
  a = (sp + sm) / (2 * q * kap); d = (sp - sm) / 2;
  [1, 'x^4 - lift(a) * 'x^3 + kap * e1 * 'x^2 - lift(d) * 'x + (q * kap)^2];
}
""")
pari(r"""
r6_planes(C, Lam, l) = {
  \\ the classes of the lattices Lam' with l Lam < Lam' < Lam of index l^2 stable under C
  my(M = Lam^(-1) * C * Lam, Mb, out = List(), n = 4);
  if(denominator(M) != 1, error("not stable"));
  Mb = Mod(M, l);
  forsubset([n, 2], piv,
    my(i = piv[1], j = piv[2], free1 = select(k -> k > i && k != j, [1..n]), free2 = select(k -> k > j, [1..n]));
    forvec(c1 = vector(#free1, k, [0, l - 1]),
      forvec(c2 = vector(#free2, k, [0, l - 1]),
        my(u = vector(n)~, w = vector(n)~, B, X);
        u[i] = 1; for(k = 1, #free1, u[free1[k]] = c1[k]);
        w[j] = 1; for(k = 1, #free2, w[free2[k]] = c2[k]);
        B = concat(Mat(u), w);
        if(matrank(concat(Mod(B, l), Mb * B)) == 2,
          X = mathnf(concat(Lam * B, l * Lam));
          listput(out, mathnf(X / content(X)))))));
  Vec(out);
}
""")
pari(r"""
r6_maximal(C, l) = {
  \\ the sublattice of index l of Z^4 stable under C (unique: Z_l[C] is local)
  my(M = Mod(C, l), lam = polrootsmod(charpoly(C), l)[1], K = lift(matker((M - lam)~)), phi, k);
  if(#K != 1, error("the order is not generated by one element locally"));
  phi = K[,1]; k = 0; for(j = 1, 4, if(phi[j] % l, k = j; break));
  mathnf(matrix(4, 4, a, b, if(b == k, if(a == k, l, 0), if(a == b, 1, if(a == k, lift(-Mod(phi[b], l) / Mod(phi[k], l)), 0)))));
}
""")
GP_quartic, GP_planes, GP_maximal = pari("r6_quartic"), pari("r6_planes"), pari("r6_maximal")

PATTERNS = {
    (Fraction(1, 2), Fraction(1, 2), Fraction(1)): "(1, 1/2, 1/2)",
    (Fraction(1, 2), Fraction(3, 4), Fraction(3, 4)): "(1/2, 3/4, 3/4)",
    (Fraction(1, 4), Fraction(1, 4), Fraction(3, 2)): "(3/2, 1/4, 1/4)",
    (Fraction(2, 3), Fraction(2, 3), Fraction(2, 3)): "(2/3, 2/3, 2/3)",
}


def pattern(info):
    """The valuations of F - lam on the three pairs of eigenvalues, from rows [e, f, self-conjugate, v]."""
    vals = []
    pairs = Counter()
    for e, f, s, v in info:
        if s:
            assert (e * f) % 2 == 0
            vals += [Fraction(v, e)] * (e * f // 2)
        else:
            pairs[(e, f, v)] += 1
    for (e, f, v), n in pairs.items():
        assert n % 2 == 0
        vals += [Fraction(v, e)] * (e * f * n // 2)
    vals = tuple(sorted(vals))
    assert len(vals) == 3 and sum(vals) == 2, "(1) the valuations do not add up to 2"
    assert vals in PATTERNS, "(1) a fifth pattern"
    return PATTERNS[vals]


def quartic_graph(f, l, start, radius=None, cap=6000):
    """Follow the steps between lattices stable under the companion matrix of f, from start."""
    C = pari.matcompanion(f)
    verts = {str(start): start}
    dist = {str(start): 0}
    nbrs = {}
    queue = [str(start)]
    for k in queue:
        ns = GP_planes(C, verts[k], l)
        nbrs[k] = [str(X) for X in ns]
        if radius is not None and dist[k] >= radius:
            continue
        for X in ns:
            if str(X) not in verts:
                verts[str(X)] = X
                dist[str(X)] = dist[k] + 1
                queue.append(str(X))
        if len(verts) > cap:
            return None
    return {k: [x for x in nbrs[k] if x in nbrs] for k in nbrs}, {k: len(nbrs[k]) for k in nbrs}


def kind(blocks):
    return {(1, 5): "leaf", (3, 3): "middle", (1, 1, 1, 3): "wide", (1, 1, 2, 2): "wide"}[blocks]


def is_tree(adj, verts):
    """Is the graph induced on verts connected with |verts| - 1 edges ?"""
    verts = set(verts)
    edges = sum(1 for v in verts for u in adj[v] if u in verts)
    if edges != 2 * (len(verts) - 1):
        return False
    start = next(iter(verts))
    seen = {start}
    stack = [start]
    while stack:
        v = stack.pop()
        for u in adj[v]:
            if u in verts and u not in seen:
                seen.add(u)
                stack.append(u)
    return seen == verts


def check_polynomial(q, e, l, sign, args):
    case = dp.Case(q, e, l, sign)
    pat = pattern(case.info)
    finite = all(case.self)
    split, f = GP_quartic(case.P, q, sign, l, 40)
    split = bool(int(split))
    quartic = {}
    if split:
        assert pari("(f, l) -> #factormod(f, l)~ == 1 && factormod(f, l)[1, 2] == 4")(f, l), "f is not a fourth power mod l"
        if finite:
            for eps, start in ((0, pari.matid(4)), (1, GP_maximal(pari.matcompanion(f), l))):
                res = quartic_graph(f, l, start)
                assert res is not None
                quartic[eps] = (len(res[0]), dp.whole_hash(res[0]))
        else:
            res = quartic_graph(f, l, pari.matid(4), radius=args.radius)
            quartic["ball"] = None if res is None else dp.ball_hash(res[0], res[1], str(pari.matid(4)), args.radius)
    out = []
    for G in case.forms(args.forms):
        seed = dp.lagrangian_seed(case, G)
        if seed is None:
            continue
        res = case.explore(G, seed, radius=None if finite else args.radius + 1, cap=args.cap)
        if res is None:
            out.append({"lattices": "too many"})
            continue
        adj, degree, inv = res
        kinds = {k: kind(inv[k][0]) for k in adj}
        for k in adj:                                   # (2): the cokernel and the leaves
            wide = inv[k][1] == (1, 1, 1, 1)
            assert wide == (kinds[k] == "wide") and (wide or inv[k][1] == (2, 2)), "(2) cokernel"
            if kinds[k] == "leaf":
                assert degree[k] == 1, "(2) a leaf with several steps"
        shape = Counter((kinds[k], inv[k][0], degree[k]) for k in adj)
        rec = {"lattices": len(adj), "closed": finite,
               "shape": [[a, list(b), d, n] for (a, b, d), n in sorted(shape.items())]}
        wide = [k for k in adj if kinds[k] == "wide"]
        rec["wide"] = len(wide)
        if finite:
            box = case.box_lattices(G, cap=args.cap)
            if box is not None:
                assert set(box) == set(adj), "the steps do not reach every lattice"
                rec["complete"] = True
            for k in adj:                               # (2): where the leaves hang
                if kinds[k] == "leaf" and kinds[adj[k][0]] == "leaf":
                    assert len(adj) == 2, "(2) two leaves joined inside a larger graph"
            if wide:                                    # (3)
                assert is_tree(adj, wide), "(3) the wide lattices do not form a tree"
            if pat == "(3/2, 1/4, 1/4)":
                assert len(adj) == 2 and not wide and rec.get("complete"), "(4) two lattices"
            if split:                                   # (5)
                got = (len(adj), dp.whole_hash(adj))
                match = [eps for eps in (0, 1) if quartic[eps] == got]
                assert match, "(5) the graph is not the graph of the quartic order"
                rec["quartic"] = match
        else:
            assert pat != "(3/2, 1/4, 1/4)"
            if split:                                   # (5), around a leaf
                dist = dp.ball(adj, str(seed), args.radius)
                leaves = sorted((dist[k], k) for k in dist if kinds[k] == "leaf")
                if leaves and quartic["ball"] is not None:
                    leaf = leaves[0][1]
                    sub = case.explore(G, pari(leaf), radius=args.radius, cap=args.cap)
                    if sub is not None:
                        got = dp.ball_hash(sub[0], sub[1], leaf, args.radius)
                        assert got == quartic["ball"], "(5) the ball around a leaf is not that of the quartic order"
                        rec["quartic"] = "ball"
        out.append(rec)
    return {"q": q, "e": e, "l": l, "eigenvalue": "+q" if sign == 1 else "-q", "primes": case.info,
            "pattern": pat, "split": split, "finite": finite, "forms": out}


def search(q, l, args, fh, total):
    for sign in ((1, -1) if args.both_signs else (1,)):
        for e, c in dp.candidates(q, l, sign, 4):
            if c != 4:
                continue
            P = cm.pol(cm.charpoly(q, e))
            if not pari.polisirreducible(P):
                continue
            if dp.predict(P, q, sign, l)[0] != 6:
                continue
            nf0 = pari.nfinit(P)
            dec = [[int(x) for x in row] for row in sv.GP_dec(nf0, q, l)]
            if any(p[3] == 2 for p in dec if p[4 if sign == 1 else 5] == 0):
                continue
            try:
                rec = check_polynomial(q, e, l, sign, args)
            except AssertionError:
                print(f"FAILED: q={q} e={e} l={l} sign={sign}", flush=True)
                raise
            key = (rec["pattern"], "square" if rec["split"] else "not a square")
            total[key] += 1
            total["lattices"] += sum(r["lattices"] for r in rec["forms"] if isinstance(r["lattices"], int))
            total["compared with the quartic order"] += any("quartic" in r for r in rec["forms"])
            if rec["pattern"] != "(3/2, 1/4, 1/4)":
                print(f"q={q} e={e} l={l} {rec['eigenvalue']} primes {rec['primes']} pattern {rec['pattern']} "
                      f"{'square' if rec['split'] else 'not a square'}: "
                      + "; ".join(f"{r['lattices']} lattices{'' if r.get('closed') else ' (ball)'}, {r.get('wide')} wide"
                                  f"{', quartic ' + str(r['quartic']) if 'quartic' in r else ''}" for r in rec["forms"]),
                      flush=True)
            if fh:
                fh.write(json.dumps(rec) + "\n")
    print(f"search q={q} l={l} done", flush=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out")
    ap.add_argument("--search", action="append", help="q,l (repeatable); default 5,3")
    ap.add_argument("--forms", type=int, default=2, help="forms tried per class of valuations")
    ap.add_argument("--radius", type=int, default=3, help="radius of the balls compared when the graph is infinite")
    ap.add_argument("--cap", type=int, default=6000)
    ap.add_argument("--both-signs", action="store_true")
    args = ap.parse_args()
    fh = open(args.out, "w") if args.out else None
    total = Counter()
    for item in args.search or ["5,3"]:
        q, l = (int(x) for x in item.split(","))
        search(q, l, args, fh, total)
    print("summary:", {str(k): v for k, v in sorted(total.items(), key=str)})


if __name__ == "__main__":
    main()
